export function getClubTheme(slugOrName: string): TeamThemeColors {
  if (!slugOrName) return CLUB_THEMES.flamengo;
  const clean = slugOrName.toLowerCase().trim();

  // 1. Direct match
  if (CLUB_THEMES[clean]) return CLUB_THEMES[clean];

  // 2. Look for partial key matches
  for (const [key, theme] of Object.entries(CLUB_THEMES)) {
    if (clean.includes(key) || key.includes(clean)) {
      return theme;
    }
  }

  // 3. Fallback default
  return {
    primary: '#10b981',
    secondary: '#ffffff',
    accent: '#10b981',
    accentHover: '#34d399',
    glow: 'rgba(16, 185, 129, 0.5)',
    gradient: 'from-emerald-950/50 via-neutral-950 to-[#0a0a0c]',
    border: 'rgba(16, 185, 129, 0.4)',
    textOnPrimary: '#ffffff',
    tabActiveBg: '#10b981',
    tabActiveText: '#022c22',
    motto: 'Tradição do Futebol Brasileiro',
    stripes: ['#10b981', '#ffffff', '#10b981'],
    surfaceBg: 'rgba(16, 185, 129, 0.08)',
    surfaceBorder: 'rgba(16, 185, 129, 0.25)',
    shieldPattern: 'Clube Oficial',
  };
}
